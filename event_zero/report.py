    L.append(f"  Linux kernel indicators: {rk.get('linux_kernel_indicators') or 'none'}")
    L.append(f"  eBPF: {rk.get('ebpf') or 'none'}"); L.append(f"  Hiding indicators: {rk.get('hiding_indicators') or 'none'}")
