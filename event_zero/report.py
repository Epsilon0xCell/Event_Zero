    L.append(f"  {r.get('timeline',{}).get('note','')}")
    L.append(""); L.append("22. GENERATED YARA RULE (review before production use)")
    L.append(r.get('generated_yara',''))
    L.append(""); L.append("BROWSER LOOKUP LINKS (hash only, nothing uploaded)")
    for name, url, note in r.get('browser_links',[]): L.append(f"  {name}: {url} ({note})")
