    L.append(f"  Carved embedded binaries: {u.get('carved') or 'none'}")
    L.append(f"  Multi-layer decoded strings: {u.get('decoded_layers') or 'none'}")
    L.append(f"  Virtualization: {u.get('virtualization',{}).get('plain_english','')}")
    L.append(f"  High entropy regions: {u.get('high_entropy_regions') or 'none'}")
    L.append(""); L.append("14. FIRMWARE AND UEFI")
    fw=r.get('firmware',{}); L.append(f"  {fw.get('plain_english','')}")
    L.append(f"  Magic hits: {fw.get('magic_hits') or 'none'}"); L.append(f"  UEFI volumes: {fw.get('uefi_volumes') or 'none'}")
    L.append(f"  DXE drivers carved: {fw.get('dxe_drivers_carved') or 'none'}"); L.append(f"  Red flags: {fw.get('red_flags') or 'none'}")
    L.append(""); L.append("15. ROOTKIT AND KERNEL")
